#!/usr/bin/env bash
# Build a WordPress.org submission tree from this checkout.
# Usage: bin/export-wporg-tree.sh [destination-dir]
# Default destination: /tmp/agent-builder
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-/tmp/agent-builder}"
IGNORE="$ROOT/.distignore"

if [[ ! -f "$IGNORE" ]]; then
	echo "Missing .distignore" >&2
	exit 1
fi

rm -rf "$DEST"
mkdir -p "$DEST"

# Translate .distignore lines into rsync --exclude patterns.
EXCLUDES=( --exclude '.git/' )
while IFS= read -r line || [[ -n "$line" ]]; do
	line="${line%%#*}"
	line="$(echo "$line" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
	[[ -z "$line" ]] && continue
	EXCLUDES+=( --exclude "$line" )
done < "$IGNORE"

rsync -a "${EXCLUDES[@]}" "$ROOT/" "$DEST/"

# Stamp the public channel so a zip built from a mixed checkout is still wporg.
mkdir -p "$DEST/includes"
cat > "$DEST/includes/dist-channel.php" <<'PHP'
<?php
// Generated by bin/export-wporg-tree.sh — public WordPress.org free edition.
// See Agentic\Distribution.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}
if ( ! defined( 'AGENTIC_DIST_CHANNEL' ) ) {
	define( 'AGENTIC_DIST_CHANNEL', 'wporg' );
}
PHP

echo "Exported WP.org tree to $DEST"
